-- User data moved from the phone and from Firestore to our own database (D-024, BE-021, BE-022).
-- Every table is keyed by the Firebase uid, which comes only from the verified ID token.

-- The app's profile (the same JSON the app keeps locally) and the device's FCM token.
-- profile is null for a row that only holds a token, so "no profile yet" stays distinguishable.
create table user_profile (
    uid         varchar(128) primary key,
    profile     jsonb,
    fcm_token   varchar(4096),
    source      varchar(20)  not null,          -- app | firestore_import
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now()
);

-- Logged meals. id is generated by the app; the latest client change wins (client_updated_at).
-- Deletions are kept as tombstones (deleted = true) so other devices learn about them.
create table meal_history (
    uid                varchar(128) not null,
    id                 varchar(64)  not null,
    name               varchar(120) not null,
    entry_type         varchar(16)  not null,   -- cooked | ate_out | logged
    meal_type          varchar(40),
    reaction           varchar(16),
    calories           integer,
    servings           integer,
    area               varchar(120),
    note               varchar(500),
    image_url          varchar(500),
    tags               jsonb        not null default '[]'::jsonb,
    logged_at          timestamptz  not null,
    client_updated_at  timestamptz  not null,
    deleted            boolean      not null default false,
    server_updated_at  timestamptz  not null default now(),
    primary key (uid, id)
);
-- Sync reads one user's changes in (server_updated_at, id) order.
create index meal_history_sync_idx on meal_history (uid, server_updated_at, id);
-- The daily retention job deletes by age.
create index meal_history_logged_at_idx on meal_history (logged_at);

-- Favourite dish names, with the latest client change winning; favorite = false is an un-favourite.
create table favorite_dish (
    uid                varchar(128) not null,
    name               varchar(120) not null,
    favorite           boolean      not null,
    client_updated_at  timestamptz  not null,
    server_updated_at  timestamptz  not null default now(),
    primary key (uid, name)
);

-- When a user last synced; accounts inactive for 24 months lose their cloud history.
create table user_activity (
    uid           varchar(128) primary key,
    last_seen_at  timestamptz  not null
);
create index user_activity_last_seen_idx on user_activity (last_seen_at);
